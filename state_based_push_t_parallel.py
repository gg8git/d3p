def evaluate_policy_vectorized(
    make_env_fn,                     # callable -> env (e.g., partial(PushTEnvAPI))
    n_envs: int = 16,
    seeds: Optional[Sequence[int]] = None,
    max_steps: int = 200,
    obs_horizon: int = 2,
    pred_horizon: int = 16,
    action_horizon: int = 8,
    stats=None,                      # your dataset.stats
    device=None,                     # your torch device
    policy=None
):
    """
    NOTE(faraz): written entirely by GPT

    Runs one episode per env (up to max_steps), no rendering (fast).
    Returns: dict(success_rate, avg_return, returns, successes)
    """
    assert stats is not None and device is not None

    # ----- Build vectorized envs with distinct seeds -----
    if seeds is None:
        seeds = np.arange(100000, 100000 + n_envs)  # deterministic default
    assert len(seeds) == n_envs

    def make_one(seed):
        def thunk():
            env = make_env_fn()
            env.seed(int(seed))
            return env
        return thunk

    venv = gym.vector.AsyncVectorEnv([make_one(s) for s in seeds])

    # ----- Reset -----
    obs, infos = venv.reset()
    # obs: (n_envs, 5)
    # Build history buffer: (n_envs, obs_horizon, obs_dim)
    obs_dim = obs.shape[-1]
    obs_hist = np.repeat(obs[:, None, :], obs_horizon, axis=1)

    # Per-env accounting
    # Instead of accumulating returns, keep track of max reward per env
    max_rewards = np.full(n_envs, -np.inf, dtype=np.float32)
    successes = np.zeros(n_envs, dtype=bool)
    dones_mask = np.zeros(n_envs, dtype=bool)

    step_count = 0
    # We'll loop until all envs done or step budget exceeded
    with tqdm(total=max_steps, desc="Parallel EnvAPI Eval", leave=False) as pbar:
        while (not np.all(dones_mask)) and (step_count < max_steps):
            
            # --------- Batch diffusion inference (B = n_envs) ---------
            # Normalize observations using your dataset stats 
            # NOTE (faraz): this is just GPT duplicating the `normalize_data` function I should replace with the actual function later
            nobs = (obs_hist - stats['obs']['min']) / (stats['obs']['max'] - stats['obs']['min'])
            nobs = nobs * 2 - 1  # to [-1, 1]
            nobs_t = torch.from_numpy(nobs).to(device, dtype=torch.float32)  # (B, H, D)
            
            naction = policy.sample(nobs_t, pred_horizon, device)
              
            # Unnormalize actions back to env's absolute [0, 512]^2
            naction_np = naction.detach().to('cpu').numpy()             # (B, T, 2)
            action_pred = ( (naction_np + 1)/2 ) * (stats['action']['max'] - stats['action']['min']) + stats['action']['min']

            # We'll apply only action_horizon steps without replanning (to match your single-env eval)
            start = obs_horizon - 1
            end = start + action_horizon
            action_chunk = action_pred[:, start:end, :]                 # (B, action_horizon, 2)

            # --------- Execute the chunk on the vector env ---------
            for t in range(action_chunk.shape[1]):
                # For done envs, feed a neutral action (ignored by many envs).
                acts = action_chunk[:, t, :]
                # If some envs are already done, avoid stepping them further
                if np.any(dones_mask):
                    acts = acts.copy()
                    acts[dones_mask] = 0.0

                next_obs, reward, terminated, truncated, info = venv.step(acts)

                # Update max reward for active envs
                active = ~dones_mask
                # Only update max_rewards for active envs
                max_rewards[active] = np.maximum(max_rewards[active], reward[active].astype(np.float32))

                # Mark success using "terminated" (task complete). "truncated" is timeout.
                newly_done = (terminated | truncated) & ~dones_mask
                successes[newly_done] = terminated[newly_done]
                dones_mask |= (terminated | truncated)

                # Maintain the obs history for active envs
                # Shift obs_hist left and append new observation for active envs
                obs_hist[active, :-1, :] = obs_hist[active, 1:, :]
                obs_hist[active, -1, :] = next_obs[active]

                obs = next_obs
                step_count += 1
                
                # Update progress bar
                pbar.update(1)
                pbar.set_postfix({
                    'step': step_count,
                    'done_envs': np.sum(dones_mask),
                    'avg_reward': f"{np.mean(max_rewards[active]):.2f}" if np.any(active) else "N/A"
                })

                # Early exit if all envs finished
                if np.all(dones_mask) or step_count >= max_steps:
                    break

    venv.close()

    # Print scores for every env
    print("Scores for each environment (max reward over all timesteps):")
    for i, score in enumerate(max_rewards):
        print(f"Env {i}: {score:.2f}")

    return {
        "success_rate": float(successes.mean()),
        "avg_return": float(max_rewards.mean()),
        "returns": max_rewards,
        "successes": successes,
    }

