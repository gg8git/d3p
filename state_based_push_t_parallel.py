class PushTEnvAPI(gym.Env):
    """
    NOTE(Faraz): GPT wrote this Wrapper around the Gymnasium API to work as a 
    drop in replacement for the one originally defined in the Push-T colab statebased notebook.

    Drop-in replacement for the PyMunk PushTEnv.
    Preserves:
      - obs: [agent_x, agent_y, block_x, block_y, block_angle]
      - action scale your policy expects: absolute targets in [0, 512]^2
      - API: reset() -> (obs, info), step(action) -> (obs, reward, terminated, truncated, info)
      - action_space / observation_space attributes (so .sample() etc. work)
    """
    metadata = {"render_modes": ["human", "rgb_array"], "video.frames_per_second": 10}
    reward_range = (0., 1.)

    def __init__(self, render_size=96, render_mode=None, seed_val=None):
        self.render_size = render_size
        self._seed = seed_val
        self.render_mode = render_mode

        # Use STATE obs for speed; pixels only for rendering (lazy).
        self._env = gym.make(
            "gym_pusht/PushT-v0", 
            obs_type="state", 
            render_mode=self.render_mode
        )
        self._act_low = self._env.action_space.low
        self._act_high = self._env.action_space.high

        # ---- Define Gym spaces to match your original env ----
        ws = 512
        self.observation_space = gym.spaces.Box(
            low=np.array([0, 0, 0, 0, 0], dtype=np.float64),
            high=np.array([ws, ws, ws, ws, np.pi * 2], dtype=np.float64),
            shape=(5,),
            dtype=np.float64,
        )
        self.action_space = gym.spaces.Box(
            low=np.array([0, 0], dtype=np.float32),
            high=np.array([ws, ws], dtype=np.float32),
            shape=(2,),
            dtype=np.float32,
        )

    # keep your old API
    def seed(self, seed=None):
        if seed is None:
            seed = int(np.random.randint(0, 25536))
        self._seed = seed
        try:
            self._env.reset(seed=seed)
        except TypeError:
            pass

    def _obs_to_vec(self, obs):
        # gym-pusht state: dict('agent_pos': (2,), 'block_pose': (3, [x,y,theta]))
        if isinstance(obs, dict) and "agent_pos" in obs and "block_pose" in obs:
            ax, ay = obs["agent_pos"]
            bx, by, th = obs["block_pose"]
            return np.array([ax, ay, bx, by, th], dtype=np.float64)
        arr = np.asarray(obs, dtype=np.float64).reshape(-1)
        if arr.shape[0] < 5:
            raise ValueError(f"Unexpected obs shape: {arr.shape}")
        return arr[:5]

    def reset(self, *, seed=None, options=None):
        if seed is not None:
            self.seed(seed)
        obs, info = self._env.reset(seed=self._seed)
        return self._obs_to_vec(obs), info

    def _scale_action(self, action):
        """
        Your policy outputs absolute cursor targets in [0,512]^2.
        Map to the wrapped env Box(low, high).
        """
        a = np.asarray(action, dtype=np.float32)
        low, high = self._act_low, self._act_high
        # Common cases
        if np.allclose(low, 0) and np.allclose(high, 1):
            return a / 512.0
        if np.allclose(low, 0) and np.allclose(high, 512):
            return a
        # Generic affine map from [0,512] -> [low, high]
        return (a / 512.0) * (high - low) + low

    def step(self, action):
        act = self._scale_action(action)
        obs, reward, terminated, truncated, info = self._env.step(act)
        return self._obs_to_vec(obs), float(reward), bool(terminated), bool(truncated), info

    def render(self, mode="rgb_array"):
        if self.render_mode is None:
            raise RuntimeError("This env was created headless. Recreate with render_mode='rgb_array'.")
        frame = self._env.render()  # frame matches current state (single env)
        import cv2
        return cv2.resize(frame, (self.render_size, self.render_size))

    def close(self):
        try: self._env.close()
        except Exception: pass


